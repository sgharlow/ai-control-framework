// Renders benchmarks/RESULTS.md from results.jsonl.
// Usage: node render-results.mjs <results.jsonl> <RESULTS.md> [findings.md]
// Aggregates are always recomputed from the jsonl; the Findings and Deviations
// sections are authored prose read from findings.md (kept alongside the data so
// re-rendering never silently invents findings).
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const [, , jsonlPath, outPath, findingsPath] = process.argv;
const rows = readFileSync(jsonlPath, "utf8")
  .split("\n")
  .filter(Boolean)
  .map((l) => JSON.parse(l));

const cohorts = ["A", "B"];
const label = { A: "Cohort A — pre-discipline era", B: "Cohort B — verification-discipline era" };

const median = (nums) => {
  if (!nums.length) return null;
  const s = [...nums].sort((a, b) => a - b);
  const m = Math.floor(s.length / 2);
  return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2;
};
const pct = (num, den) => (den === 0 ? "n/a" : `${Math.round((100 * num) / den)}% (${num}/${den})`);

const esc = (s) => String(s ?? "").replace(/\|/g, "\\|");

let md = `# Benchmark results (Sprint 9)

Generated by \`benchmarks/run-benchmark.sh\` per [METHODOLOGY.md](METHODOLOGY.md).
Pinned commits: [\`data/repos.lock\`](data/repos.lock) · raw rows: [\`data/results.jsonl\`](data/results.jsonl) · full M1 hit lists: \`data/raw/m1-<repo>.txt\`.

> **Read [METHODOLOGY.md — Limitations](METHODOLOGY.md#limitations-read-before-quoting-any-number) before quoting any number.**
> Observational, N≈19, one developer, static proxies only. DRS runs low at rest by design.

`;

for (const c of cohorts) {
  const rs = rows.filter((r) => r.cohort === c);
  md += `## ${label[c]}\n\n`;
  md += `| Repo | SHA | M1 mock hits (files) | M2 unverifiable claims | M3 CI real | M4 builds | M5 DRS | M6 license | M6 lockfile |\n`;
  md += `|---|---|---|---|---|---|---|---|---|\n`;
  for (const r of rs) {
    if (r.error) {
      md += `| ${r.name} | ${(r.sha || "").slice(0, 7)} | — | — | — | — | — | — | ERROR: ${esc(r.error)} |\n`;
      continue;
    }
    md += `| ${r.name} | ${r.sha.slice(0, 7)} | ${r.m1_hits} (${r.m1_file_count}) | ${r.m2_flags.length} | ${
      r.m3_ci ? "yes" : "no"
    } (\`${esc(r.m3_raw)}\`) | ${r.m4_builds === "n/a" ? "n/a" : r.m4_builds ? "yes" : "NO"} — ${esc(
      r.m4_detail?.split(";")[0] ?? ""
    )} | ${typeof r.m5_drs === "number" ? r.m5_drs : "error"} | ${r.m6_license ? "yes" : "no"} | ${
      r.m6_lockfile === "n/a" ? "n/a" : r.m6_lockfile ? "yes" : "no"
    } |\n`;
  }
  md += `\n`;
}

md += `## Cohort aggregates\n\n| Aggregate | Cohort A | Cohort B |\n|---|---|---|\n`;
const agg = {};
for (const c of cohorts) {
  const rs = rows.filter((r) => r.cohort === c && !r.error);
  const drs = rs.map((r) => r.m5_drs).filter((v) => typeof v === "number");
  const buildable = rs.filter((r) => r.m4_builds !== "n/a");
  agg[c] = {
    n: rs.length,
    errors: rows.filter((r) => r.cohort === c && r.error).length,
    medianDrs: median(drs),
    buildPct: pct(buildable.filter((r) => r.m4_builds === true).length, buildable.length),
    ciPct: pct(rs.filter((r) => r.m3_ci === true).length, rs.length),
    mockPct: pct(rs.filter((r) => r.m1_hits > 0).length, rs.length),
    claimPct: pct(rs.filter((r) => r.m2_flags.length > 0).length, rs.length),
    licPct: pct(rs.filter((r) => r.m6_license === true).length, rs.length),
  };
}
const rowsAgg = [
  ["Repos measured", (c) => `${agg[c].n}${agg[c].errors ? ` (+${agg[c].errors} failed)` : ""}`],
  ["Median DRS (M5)", (c) => agg[c].medianDrs ?? "n/a"],
  ["% buildable (M4, n/a excluded)", (c) => agg[c].buildPct],
  ["% with real CI (M3: workflows + latest run success)", (c) => agg[c].ciPct],
  ["% with mock residue (M1 hits > 0)", (c) => agg[c].mockPct],
  ["% with unverifiable claims (M2 flags > 0)", (c) => agg[c].claimPct],
  ["% with LICENSE (M6)", (c) => agg[c].licPct],
];
for (const [labelTxt, fn] of rowsAgg) md += `| ${labelTxt} | ${fn("A")} | ${fn("B")} |\n`;
md += `\n`;

if (findingsPath && existsSync(findingsPath)) {
  md += readFileSync(findingsPath, "utf8").trim() + "\n";
} else {
  md += `## Findings\n\n_TODO: authored findings not yet written (benchmarks/data/findings.md missing)._\n`;
}

writeFileSync(outPath, md, { encoding: "utf8" });
console.log(`Wrote ${outPath} (${rows.length} rows)`);
